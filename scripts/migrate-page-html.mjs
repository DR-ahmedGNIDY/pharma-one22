async function run() {
  await mongoose.connect(MONGODB_URI);

  let updated = 0;
  let skipped = 0;

  for (const slug of Object.keys(htmlDefaults)) {
    const page = await Page.findOne({ slug });

    if (!page) {
      console.log(`[skip] ${slug}: no document found`);
      skipped++;
      continue;
    }

    if (page.content === markdownDefaults[slug]) {
      page.content = htmlDefaults[slug];
      await page.save();
      console.log(`[updated] ${slug}`);
      updated++;
    } else {
      console.log(`[skip] ${slug}: content already customized, left untouched`);
      skipped++;
    }
  }

  console.log(`\nDone. Updated: ${updated}, skipped: ${skipped}`);
  await mongoose.disconnect();
}

run().catch((err) => {
  console.error("Migration failed:", err.message);
  process.exit(1);
});
